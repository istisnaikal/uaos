//! SPDX license headers. Every source and configuration file carries
//! `SPDX-License-Identifier: Apache-2.0` in its first lines, so licensing is unambiguous per
//! file (plan §5). Formats that cannot carry comments (JSON, lock files) and tool-generated
//! files are covered by the root LICENSE and listed here explicitly.

use std::path::Path;

use crate::util::{rel, walk_files};

const NEEDLE: &str = "SPDX-License-Identifier: Apache-2.0";
const HEADER_WINDOW_LINES: usize = 5;
const CHECKED_EXTENSIONS: &[&str] = &["rs", "toml", "yml", "yaml", "sh", "ps1", "py"];

/// Files that cannot or should not carry a header, with the reason.
const EXEMPT_PREFIXES: &[(&str, &str)] = &[(
    "supply-chain/",
    "regenerated by cargo-vet, which does not preserve comments",
)];

pub(crate) fn check(root: &Path) -> Result<(), String> {
    let mut missing = Vec::new();
    let mut checked = 0usize;
    for path in walk_files(root)? {
        let relative = rel(root, &path);
        let ext = path.extension().and_then(|e| e.to_str()).unwrap_or_default();
        if !CHECKED_EXTENSIONS.contains(&ext) || EXEMPT_PREFIXES.iter().any(|(p, _)| relative.starts_with(p)) {
            continue;
        }
        checked += 1;
        let text = std::fs::read_to_string(&path).map_err(|e| format!("{relative}: {e}"))?;
        if !text.lines().take(HEADER_WINDOW_LINES).any(|l| l.contains(NEEDLE)) {
            missing.push(relative);
        }
    }
    if missing.is_empty() {
        println!("xtask headers: {checked} files carry an SPDX header");
        Ok(())
    } else {
        Err(format!(
            "{} file(s) lack `{NEEDLE}` in their first {HEADER_WINDOW_LINES} lines (SPDX header):\n  {}",
            missing.len(),
            missing.join("\n  ")
        ))
    }
}
